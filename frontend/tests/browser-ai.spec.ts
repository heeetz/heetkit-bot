test('response language rejects an excluded fallback and saves a corrected policy', async ({ page }) => {
  await server(page)
  type Policy = { mode: string; allowed_languages: string[]; fallback_language: string }
  let settings: Policy = { mode: 'auto', allowed_languages: ['en', 'uk'], fallback_language: 'en' }
  let writes = 0
  await page.route('**/v1/ai/language', async (route) => {
    if (route.request().method() === 'POST') {
      writes += 1
      settings = route.request().postDataJSON()
    }
    await route.fulfill({ json: { ok: true, settings, active_policy: settings.mode,
      languages: [{ code: 'en', label: 'English' }, { code: 'uk', label: 'Ukrainian' }],
    } })
  })
  await signIn(page)
  await navigate(page, 'AI')
  const language = await openAIBehaviorSection(page, 'Response languages')
  const mode = language.getByLabel('Response language mode')
  await expect(mode).toHaveAttribute('data-value', 'auto')
  await selectOption(mode, 'limited')
  await language.getByLabel('English', { exact: true }).uncheck()
  const save = language.getByRole('button', { name: 'Save language settings' })
  await expect(save).toBeDisabled()
  expect(writes).toBe(0)
  await language.getByLabel('English', { exact: true }).check()
  await language.getByLabel('Ukrainian', { exact: true }).uncheck()
  await save.click()
  await expect.poll(() => settings).toEqual({ mode: 'limited', allowed_languages: ['en'], fallback_language: 'en' })
  await closeAIBehavior(page)
  await navigate(page, 'Dashboard')
  await navigate(page, 'AI')
  await openAIBehaviorSection(page, 'Response languages')
  await expect(mode).toHaveAttribute('data-value', 'limited')
  await expect(language.getByLabel('Ukrainian', { exact: true })).not.toBeChecked()
})

