import { expect, test } from '@playwright/test'
import { adminToken, closeAIBehavior, login, navigate, openAIBehaviorSection, server, sessionToken, signIn } from './browser-fixture'

test('browser login keeps tokens out of cookies, URLs and request bodies; a tab session survives reload only', async ({ page, context }) => {
  const api = await server(page)
  await context.addCookies([{ name: 'unrelated', value: 'cookie', url: 'http://127.0.0.1:5174' }])
  await page.addInitScript(() => {
    const nativeFetch = window.fetch
    Object.assign(window, { fetchOptions: [] })
    window.fetch = (input, options) => {
      Reflect.get(window, 'fetchOptions').push({ credentials: options?.credentials, redirect: options?.redirect })
      return nativeFetch(input, options)
    }
  })
  await page.goto('/tests/browser.fixture.html')
  expect(api.calls).toEqual([])
  await login(page)
  await expect(page.getByLabel('Administrator token')).toHaveCount(0)
  expect(api.calls[0]).toEqual({ method: 'POST', path: '/v1/session', body: {}, authorization: `Bearer ${adminToken}` })
  expect(api.calls.slice(1).every((call) => call.authorization === `Bearer ${sessionToken}`)).toBe(true)
  expect(api.calls.every((call) => !JSON.stringify(call.body).includes(adminToken) && !JSON.stringify(call.body).includes(sessionToken))).toBe(true)
  expect(page.url()).not.toContain(adminToken)
  expect(await page.evaluate(() => ({ local: { ...localStorage }, session: { ...sessionStorage }, cookie: document.cookie }))).toEqual({ local: {}, session: { 'heetkit.session': sessionToken }, cookie: 'unrelated=cookie' })
  expect(await page.evaluate(() => Reflect.get(window, 'fetchOptions').every((options: { credentials: string; redirect: string }) => options.credentials === 'omit' && options.redirect === 'error'))).toBe(true)
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Dashboard', exact: true })).toBeVisible()
  expect(api.calls.some((call) => call.method === 'GET' && call.path === '/v1/session' && call.authorization === `Bearer ${sessionToken}`)).toBe(true)
  const fresh = await context.newPage()
  await fresh.goto('/tests/browser.fixture.html')
  await expect(fresh.getByRole('heading', { name: 'Sign in to server' })).toBeVisible()
  await fresh.close()
  await page.getByRole('button', { name: 'Sign out', exact: true }).click()
  expect(await page.evaluate(() => ({ ...sessionStorage }))).toEqual({})
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Sign in to server' })).toBeVisible()
})

test('remembered sign-in survives a new tab; an expired session or sign-out everywhere forgets it', async ({ page, context }) => {
  const api = await server(page)
  await page.goto('/tests/browser.fixture.html')
  await page.getByLabel('Administrator token').fill(adminToken)
  await page.getByText('Remember me on this device').click()
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Dashboard', exact: true })).toBeVisible()
  expect(api.calls[0]).toEqual({ method: 'POST', path: '/v1/session', body: { remember: true }, authorization: `Bearer ${adminToken}` })
  expect(await page.evaluate(() => ({ local: { ...localStorage }, session: { ...sessionStorage } }))).toEqual({ local: { 'heetkit.session': sessionToken }, session: {} })
  const other = await context.newPage()
  await server(other)
  await other.goto('/tests/browser.fixture.html')
  await expect(other.getByRole('heading', { name: 'Dashboard', exact: true })).toBeVisible()
  await other.getByRole('button', { name: 'Sign out on all devices' }).click()
  await expect(other.getByRole('heading', { name: 'Sign in to server' })).toBeVisible()
  expect(await other.evaluate(() => ({ ...localStorage }))).toEqual({})
  await other.close()
  await page.evaluate((token) => localStorage.setItem('heetkit.session', token), sessionToken)
  api.expire()
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Sign in to server' })).toBeVisible()
  expect(await page.evaluate(() => ({ ...localStorage }))).toEqual({})
})

test('401 expiration removes editors and their drafts; failed logout still removes local access', async ({ page }) => {
  await page.clock.install()
  const api = await server(page)
  await signIn(page)
  await navigate(page, 'AI')
  await openAIBehaviorSection(page, 'Profile instructions')
  await page.locator('#ai-profile-instructions textarea').fill('Private unsaved draft')
  api.expire()
  await page.clock.fastForward(5100)
  await expect(page.getByRole('heading', { name: 'Sign in to server' })).toBeVisible()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  api.expire(false)
  await login(page)
  await page.getByRole('button', { name: 'AI', exact: true }).click()
  await openAIBehaviorSection(page, 'Profile instructions')
  await expect(page.locator('#ai-profile-instructions textarea')).toHaveValue('Saved instructions')
  await closeAIBehavior(page)
  api.fail('/v1/session/logout')
  await page.getByRole('button', { name: 'Sign out', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Sign in to server' })).toBeVisible()
})

test('Playground keeps a late result private after logout', async ({ page }) => {
  await server(page)
  let release!: () => void
  const activeRequest = new Promise<void>((resolve) => { release = resolve })
  let arrived = false
  let delivered = false
  await page.route('**/v1/ops/get_ai_playground_result', async (route) => {
    arrived = true
    await activeRequest
    await route.fulfill({ json: { ok: true, status: 'success', text: 'Private synthetic answer' } })
    delivered = true
  })
  await signIn(page)
  await navigate(page, 'AI')
  const playground = page.locator('#ai-playground')
  await playground.getByLabel('Playground prompt').fill('Private operator prompt')
  await playground.getByRole('button', { name: 'Test prompt' }).click()
  await expect.poll(() => arrived).toBe(true)
  await page.getByRole('button', { name: 'Sign out', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Sign in to server' })).toBeVisible()
  release()
  await expect.poll(() => delivered).toBe(true)
  await login(page)
  await navigate(page, 'AI')
  await expect(playground.getByLabel('Playground prompt')).toHaveValue('')
  await expect(page.getByText('Private synthetic answer')).toHaveCount(0)
})

test('shared help responds to hover, Escape, and keyboard focus', async ({ page }) => {
  await server(page)
  await signIn(page)
  await navigate(page, 'Logs')
  const help = page.getByRole('button', { name: 'Help: What logs keep' })
  const tooltip = page.getByRole('tooltip')
  await page.clock.install()
  await help.hover()
  await page.clock.runFor(799)
  await expect(tooltip).toHaveCount(0)
  await page.clock.runFor(101)
  await expect(tooltip).toBeVisible()
  await tooltip.hover()
  await page.clock.runFor(300)
  await expect(tooltip).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(tooltip).toHaveCount(0)

  await page.mouse.move(1, 1)
  await page.keyboard.press('Tab')
  await help.focus()
  await expect(tooltip).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(tooltip).toHaveCount(0)
  await expect(help).toBeFocused()
})

test('keyboard navigation expands the AI submenu and reaches its sections', async ({ page }) => {
  await server(page)
  await signIn(page)
  const navigation = page.getByRole('navigation', { name: 'Main navigation' })
  const parent = navigation.getByRole('button', { name: 'AI', exact: true })
  await parent.focus()
  await parent.press('Space')
  await expect(parent).toHaveAttribute('aria-expanded', 'true')
  await page.keyboard.press('Tab')
  await page.keyboard.press('Tab')
  const behavior = navigation.getByRole('button', { name: 'AI behavior', exact: true })
  await expect(behavior).toBeFocused()
  await behavior.press('Enter')
  await expect(behavior).toHaveAttribute('aria-current', 'location')
  await page.keyboard.press('Tab')
  const playground = navigation.getByRole('button', { name: 'Playground', exact: true })
  await expect(playground).toBeFocused()
  await playground.press('Enter')
  await expect(playground).toHaveAttribute('aria-current', 'location')
  await expect(page.getByLabel('Playground prompt')).toBeVisible()
})

test('a dismissed AI load error preserves navigation to the existing AI sections', async ({ page }) => {
  const api = await server(page)
  api.fail('/v1/ops/get_ai_language_settings')
  await signIn(page)
  await navigate(page, 'AI')
  const error = page.getByRole('alert')
  await expect(error).toBeVisible()
  await error.getByRole('button', { name: 'Dismiss message' }).click()
  await expect(error).toHaveCount(0)
  await navigate(page, 'AI behavior')
  await expect(page.getByRole('heading', { name: 'AI behavior' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Edit personalities' })).toBeEnabled()
})
