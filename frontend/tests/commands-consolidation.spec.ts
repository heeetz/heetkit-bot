import { expect, test, type Locator } from '@playwright/test'
import { selectOption } from './select-helpers'

async function bounds(locator: Locator) {
  const box = await locator.boundingBox()
  expect(box).not.toBeNull()
  return box!
}

for (const width of [1280, 390, 320]) {
  test(`Desktop command consolidation and growing restriction catalog at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 1000 })
    await page.goto('/tests/commands.fixture.html?extended&manyCommands&shell')
    await page.getByRole('navigation').getByRole('button', { name: 'Commands', exact: true }).click()
    const ask = page.locator('#command-editor-ask')
    await ask.getByRole('button', { name: 'Edit !ask', exact: true }).click()
    const primary = await bounds(ask.getByLabel('Primary chat name', { exact: true }))
    const display = await bounds(ask.getByLabel('Name in UI', { exact: true }))
    const aliases = await bounds(ask.getByLabel('Aliases, separated by commas', { exact: true }))
    const permission = await bounds(ask.getByLabel('Permission', { exact: true }))
    expect(permission.y).toBeGreaterThan(aliases.y)
    await expect(ask.getByRole('combobox', { name: 'Response type' })).toHaveCount(0)
    if (width === 1280) {
      expect(primary.y).toBe(display.y); expect(display.y).toBe(aliases.y)
      expect(aliases.width / primary.width).toBeGreaterThan(1.8)
    } else {
      expect(display.y).toBeGreaterThan(primary.y)
      expect(aliases.y).toBeGreaterThan(display.y)
    }
    await ask.screenshot({ path: `node_modules/.tmp/consolidation-ask-${width}.png` })
    const restrictions = page.locator('#command-restrictions')
    const order = await page.evaluate(() => {
      const list = document.querySelector('#builtin-commands > .command-list')!
      const restrictions = document.querySelector('#command-restrictions')!
      const removed = document.querySelector('#removed-commands')!
      return [Boolean(list.compareDocumentPosition(restrictions) & Node.DOCUMENT_POSITION_FOLLOWING), Boolean(restrictions.compareDocumentPosition(removed) & Node.DOCUMENT_POSITION_FOLLOWING)]
    })
    expect(order).toEqual([true, true])
    await restrictions.getByRole('button', { name: 'Add restriction' }).click()
    await restrictions.getByLabel('Twitch username').fill('viewer')
    await selectOption(restrictions.getByLabel('Expiry', { exact: true }), 'date')
    await restrictions.getByLabel('Expires at').fill('2027-01-01T12:00')
    const username = await bounds(restrictions.getByLabel('Twitch username'))
    const expiry = await bounds(restrictions.getByRole('combobox', { name: 'Expiry', exact: true }))
    const note = await bounds(restrictions.getByLabel('Private note'))
    const group = await bounds(restrictions.getByRole('group', { name: 'Affected commands' }))
    if (width === 1280) expect(username.y).toBe(expiry.y)
    expect(note.y).toBeGreaterThan(expiry.y); expect(group.y).toBeGreaterThan(note.y)
    const choices = restrictions.locator('.restriction-choice-grid label')
    await expect(choices).toHaveCount(42)
    await expect(restrictions.getByRole('checkbox', { name: 'Manage !optout', exact: true })).toHaveCount(0)
    await restrictions.screenshot({ path: `node_modules/.tmp/consolidation-restrictions-${width}.png` })
    await page.locator('#administrative-commands > summary').click()
    const erase = page.locator('#command-editor-erase')
    await erase.getByRole('button', { name: 'Edit !erase', exact: true }).click()
    await erase.getByLabel('Permission', { exact: true }).click()
    await expect(page.getByRole('option').locator('span:first-child')).toHaveText(['moderator', 'broadcaster'])
    await page.keyboard.press('Escape')
    await expect(erase.getByRole('combobox', { name: 'Response type' })).toHaveCount(0)
    const optout = page.locator('#optout-management')
    await optout.getByRole('button', { name: 'Manage !optout', exact: true }).click()
    await expect(optout).toContainText('No opted-out users.')
    await page.evaluate(() => Reflect.get(window, 'addChatOptout')())
    await optout.getByRole('button', { name: 'Refresh', exact: true }).click()
    await expect(optout.locator('tbody tr')).toHaveCount(1)
    await optout.screenshot({ path: `node_modules/.tmp/consolidation-optouts-${width}.png` })
    await expect(optout.locator('.state-pill, .mini-badge, .switch-input')).toHaveCount(0)
    await page.locator('#administrative-commands').screenshot({ path: `node_modules/.tmp/consolidation-administration-${width}.png` })
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(width)
  })
}

test('global AI scope and unresolved legacy rules remain visible and manageable', async ({ page }) => {
  await page.goto('/tests/commands.fixture.html?extended&legacyRestriction')
  const panel = page.locator('#command-restrictions')
  await expect(panel).toContainText('Identity unresolved')
  await panel.getByRole('button', { name: 'Verify / edit' }).click()
  await expect(panel.getByLabel('Twitch username')).toBeDisabled()
  await expect(panel.getByLabel('Private note')).toHaveValue('Preserved operator note')
  await panel.getByRole('button', { name: 'Save restriction' }).click()
  await expect(panel.getByRole('button', { name: 'Verify / edit' })).toHaveCount(0)
  await panel.getByRole('button', { name: 'Add restriction' }).click()
  await panel.getByLabel('Twitch username').fill('globalviewer')
  await panel.getByLabel('Block AI questions across all channels in this profile').check()
  await expect(panel.getByRole('checkbox', { name: '!ask', exact: true })).toBeChecked()
  await expect(panel.getByRole('checkbox', { name: '!ping', exact: true })).toBeDisabled()
  await panel.getByRole('button', { name: 'Save restriction' }).click()
  await expect(panel).toContainText('Global AI: all profile channels')
  const calls = await page.evaluate(() => Reflect.get(window, 'commandCalls'))
  expect(calls.at(-1)[1]).toMatchObject({ scope: 'global_ai', command_ids: ['ask'] })
})

test('optout add, duplicate, withdrawal confirmation, historic metadata, paging and chat refresh', async ({ page }) => {
  await page.goto('/tests/commands.fixture.html?extended&manyOptouts')
  await page.locator('#administrative-commands > summary').click()
  const panel = page.locator('#optout-management')
  await panel.getByRole('button', { name: 'Manage !optout', exact: true }).click()
  await expect(panel.locator('tbody tr')).toHaveCount(50)
  await expect(panel.locator('tbody tr').first()).toContainText('Username unavailable')
  await expect(panel.locator('tbody tr').first()).toContainText('Historical date unknown')
  await expect(panel.locator('tbody tr').first().locator('td').first()).toHaveText('1')
  await panel.getByRole('button', { name: 'Next', exact: true }).click()
  await expect(panel.locator('tbody tr').first().locator('td').first()).toHaveText('51')
  await panel.getByLabel('Twitch username', { exact: true }).fill('operatorviewer')
  await panel.getByRole('button', { name: 'Add', exact: true }).click()
  await expect(panel.getByLabel('Twitch username', { exact: true })).toHaveValue('')
  await panel.getByLabel('Twitch username', { exact: true }).fill('operatorviewer')
  await panel.getByRole('button', { name: 'Add', exact: true }).click()
  await expect(panel.getByRole('alert')).toContainText('already opted out')
  await panel.getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(panel.getByLabel('Twitch username', { exact: true })).toBeFocused()
  await panel.getByLabel('Search opted-out users').fill('operatorviewer')
  await expect(panel.locator('tbody tr')).toHaveCount(1)
  await panel.getByRole('button', { name: /Withdraw opt-out 1 for operatorviewer/ }).click()
  await expect(page.getByRole('dialog')).toContainText('Future data storage will be allowed')
  await page.getByRole('dialog').getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(panel.locator('tbody tr')).toHaveCount(1)
  await panel.getByRole('button', { name: /Withdraw opt-out 1 for operatorviewer/ }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Confirm', exact: true }).click()
  await expect(panel).toContainText('No opted-out users match this search.')
  await page.evaluate(() => Reflect.get(window, 'addChatOptout')())
  await panel.getByLabel('Search opted-out users').fill('chatviewer')
  await expect(panel.locator('tbody tr')).toHaveCount(1)
  await panel.getByLabel('Twitch username', { exact: true }).fill('unsaved_draft')
  await panel.getByRole('button', { name: 'Refresh', exact: true }).click()
  await expect(panel.getByLabel('Twitch username', { exact: true })).toHaveValue('unsaved_draft')
  await panel.getByRole('button', { name: 'Help: !optout management' }).focus()
  await expect(page.getByRole('tooltip')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(panel.getByRole('button', { name: 'Help: !optout management' })).toBeFocused()
})

