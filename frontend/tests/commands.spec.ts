import { expect, test, type Page } from '@playwright/test'
import { selectOption } from './select-helpers'

function commandRow(page: Page, name: string) {
  return page.getByRole('row').filter({ has: page.getByRole('rowheader').getByText(name, { exact: true }) })
}

async function expandCommand(page: Page, name: string, primaryName = name) {
  await page.getByRole('button', { name: `Edit !${primaryName}`, exact: true }).click()
  return page.locator(`#command-editor-${name}`)
}

async function calls(page: Page) {
  return page.evaluate(() => Reflect.get(window, 'commandCalls'))
}

async function respondToConfirmation(page: Page, choice: 'Confirm' | 'Cancel') {
  const dialog = page.locator('dialog.confirmation-dialog[open]')
  await expect(dialog).toBeVisible()
  await dialog.getByRole('button', { name: choice, exact: true }).click()
  await expect(dialog).toHaveCount(0)
}

