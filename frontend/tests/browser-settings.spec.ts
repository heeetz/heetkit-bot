import { expect, test } from '@playwright/test'
import { expectNoOverflow, login, navigate, openSection, server, signIn } from './browser-fixture'

test('Settings saves Twitch identity and completes paste-mode authorization after canceling a draft', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 900 })
  const api = await server(page)
  api.setTwitch({ saved_bot_authorization: false, setup_complete: false, authorization_status: 'missing' })
  await page.addInitScript(() => { window.open = () => null })
  await signIn(page)
  await navigate(page, 'Settings')
  await expect(page.locator('#twitch-settings').getByRole('button', { name: 'Twitch connection', exact: true })).toHaveAttribute('aria-expanded', 'false')
  await openSection(page.locator('#twitch-settings').getByRole('button', { name: 'Twitch connection', exact: true }))
  await expect(page.getByRole('heading', { name: 'Settings', level: 1 })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Twitch connection', exact: true })).toBeVisible()

  await openSection(page.getByRole('button', { name: 'Twitch application', exact: true }))
  const connection = page.locator('#twitch-settings')
  const clientId = connection.getByLabel('Client ID', { exact: true })
  const save = connection.getByRole('button', { name: 'Save Twitch settings', exact: true })
  await clientId.fill('')
  await save.click()
  await expect(page.getByRole('alert')).toBeVisible()
  expect(api.calls.some(({ path }) => path === '/v1/ops/update_server_twitch_settings')).toBe(false)
  await clientId.fill('new-client')
  await connection.getByLabel('Bot account login', { exact: true }).fill('newbot')
  await connection.getByLabel('Bot account user ID', { exact: true }).fill('101')
  await connection.getByLabel('Target channel login', { exact: true }).fill('newchannel')
  await connection.getByLabel('Target channel user ID', { exact: true }).fill('201')
  await expectNoOverflow(page)
  page.once('dialog', (dialog) => dialog.accept())
  await save.click()
  await expect.poll(() => api.calls.find(({ path }) => path === '/v1/ops/update_server_twitch_settings')?.body).toEqual({
    client_id: 'new-client', bot_username: 'newbot', bot_user_id: '101', channel: 'newchannel', channel_user_id: '201',
})
  await expect(page.getByRole('status')).toBeVisible()
  await expect(clientId).toHaveValue('new-client')

  const connect = page.getByRole('button', { name: 'Connect Twitch', exact: true })
  const callback = page.getByLabel('Callback URL', { exact: true })
  const complete = page.getByRole('button', { name: 'Complete authorization', exact: true })
  await connect.click()
  const fallback = page.getByRole('link', { name: 'Open Twitch authorization' })
  await expect(fallback).toHaveAttribute('href', 'https://id.twitch.tv/oauth2/authorize?client_id=synthetic')
  await expect(fallback).toHaveAttribute('rel', 'noopener noreferrer')
  await callback.fill('http://localhost:8765/oauth/callback?code=discarded&state=synthetic')
  await page.getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(callback).toHaveCount(0)
  expect(api.calls.some(({ path }) => path === '/v1/ops/cancel_twitch_authorization')).toBe(true)

  await connect.click()
  await expect(callback).toHaveValue('')
  api.setOAuthComplete({ ok: false, error: 'Synthetic authorization rejection' })
  await callback.fill('http://localhost:8765/oauth/callback?error=access_denied&state=synthetic')
  await complete.click()
  await expect(page.getByRole('alert')).toBeVisible()
  await expect(callback).toHaveValue('')
  api.setOAuthComplete({ ok: true })
  await connect.click()
  const callbackUrl = 'http://localhost:8765/oauth/callback?code=synthetic&state=synthetic'
  await callback.fill(callbackUrl)
  await complete.click()
  await expect(callback).toHaveCount(0)
  expect(api.calls.filter(({ path }) => path === '/v1/ops/complete_twitch_authorization').at(-1)?.body).toEqual({ callback_url: callbackUrl })
  await expect(fallback).toHaveCount(0)
})

