test('Twitch instructions preserve a draft and the callback can be copied without clipboard permission', async ({ page }) => {
  await page.addInitScript(() => {
    Object.defineProperty(navigator, 'clipboard', { value: undefined })
    document.execCommand = (command) => {
      Reflect.set(window, 'copied', [command, (document.activeElement as HTMLTextAreaElement).value])
      return true
    }
  })
  await server(page)
  await signIn(page)
  await navigate(page, 'Settings')
  await openSection(page.locator('#twitch-settings').getByRole('button', { name: 'Twitch connection', exact: true }))
  const connection = page.locator('#twitch-settings')
  const target = connection.getByLabel('Target channel login', { exact: true })
  await target.fill('draftchannel')
  const instructions = page.getByRole('button', { name: 'Setup guide', exact: true })
  await instructions.press('Enter')
  const help = page.getByRole('dialog', { name: 'Twitch setup instructions' })
  await expect(help).toBeVisible()
  await help.getByRole('button', { name: 'Close setup instructions' }).click()
  await expect(instructions).toBeFocused()
  await expect(target).toHaveValue('draftchannel')

  await openSection(connection.getByRole('button', { name: 'Twitch application', exact: true }))
  await connection.getByRole('button', { name: 'Copy OAuth callback URL' }).click()
  expect(await page.evaluate(() => Reflect.get(window, 'copied'))).toEqual(['copy', 'http://localhost:8765/oauth/callback'])
  await expect(target).toHaveValue('draftchannel')
})

test('Server Skip AI persists and finishes setup while waiting for a stream', async ({ page }) => {
  const api = await server(page, { mode: 'stream_only', stream_status: 'offline' },
    { running: false, twitch_connected: false, twitch_connection_state: 'stopped' }, false)
  api.setTwitch({ saved_bot_authorization: false })
  await page.goto('/tests/browser.fixture.html')
  await login(page)
  const checklist = page.getByRole('article', { name: 'Setup checklist' })
  const skip = checklist.getByRole('button', { name: 'Skip AI for now' })
  await skip.click()
  await expect(checklist).toBeVisible()
  await expect(skip).toHaveCount(0)
  await page.reload()
  await login(page)
  await expect(skip).toHaveCount(0)
  await expect(checklist).toBeVisible()
  api.setTwitch({ saved_bot_authorization: true })
  await page.getByRole('button', { name: 'Settings', exact: true }).click()
  await page.getByRole('button', { name: 'Dashboard', exact: true }).click()
  await expect.poll(() => api.calls.filter((call) => call.path.endsWith('_setup_guide')).length).toBeGreaterThan(2)
  await expect(checklist).toHaveCount(0)
})

test('Twitch redirect authorization follows the signed-in attempt without requesting pasted codes', async ({ page }) => {
  const api = await server(page)
  const origin = 'https://server.example-tailnet.ts.net'
  api.setTwitch({ management_url: origin,
    oauth_callback_url: `${origin}/oauth/callback`,
    authorization_mode: 'redirect', authorization_attempt: 'pending' })
  await page.goto('/tests/browser.fixture.html')
  await login(page)
  await page.getByRole('button', { name: 'Settings', exact: true }).click()
  await openSection(page.locator('#twitch-settings').getByRole('button', { name: 'Twitch connection', exact: true }))
  await openSection(page.getByRole('button', { name: 'Twitch application', exact: true }))
  await expect(page.locator('code').filter({ hasText: `${origin}/oauth/callback` })).toBeVisible()
  await page.getByRole('button', { name: 'Connect Twitch', exact: true }).click()
  await expect(page.getByLabel('Callback URL', { exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Complete authorization', exact: true })).toHaveCount(0)
  const authorization = page.getByRole('link', { name: 'Open Twitch authorization' })
  await expect(authorization).toBeVisible()
  api.setTwitch({ authorization_attempt: 'completed' })
  await expect(authorization).toHaveCount(0)
  expect(api.calls.some((call) => call.path === '/v1/ops/complete_twitch_authorization')).toBe(false)
  expect(await page.evaluate(() => [localStorage.length, sessionStorage.length])).toEqual([0, 0])

  api.setTwitch({ authorization_attempt: 'pending' })
  await page.getByRole('button', { name: 'Connect Twitch', exact: true }).click()
  api.setTwitch({ authorization_attempt: 'failed' })
  await expect(page.getByRole('alert')).toBeVisible()
  api.setTwitch({ authorization_attempt: 'pending' })
  await page.getByRole('button', { name: 'Connect Twitch', exact: true }).click()
  api.setTwitch({ authorization_attempt: 'expired' })
  await expect(page.getByRole('alert')).toBeVisible()
})

test('a managed Twitch credential is replaced, tested and removed without losing other edits', async ({ page }) => {
  const api = await server(page)
  api.setTwitchCredential({ configured: false, managed: true, source: 'missing' })
  await signIn(page)
  await navigate(page, 'Settings')
  await openSection(page.locator('#twitch-settings').getByRole('button', { name: 'Twitch connection', exact: true }))
  const connection = page.locator('#twitch-settings')
  await openSection(connection.getByRole('button', { name: 'Twitch application' }))
  const secret = connection.getByLabel('Twitch client secret', { exact: true })
  const target = connection.getByLabel('Target channel login', { exact: true })
  await target.fill('unsaved_target')
  await secret.fill('synthetic-twitch-secret')
  await connection.getByRole('button', { name: 'Add secret' }).click()
  await expect(secret).toHaveValue('')
  const check = connection.getByRole('button', { name: 'Test saved secret' })
  await check.click()
  await expect.poll(() => api.calls.filter(({ path }) => path.endsWith('_credential')).length).toBe(2)
  await connection.getByText('Secret actions', { exact: true }).click()
  page.once('dialog', (dialog) => dialog.accept())
  await connection.getByRole('button', { name: 'Remove secret' }).click()
  await expect(check).toBeDisabled()
  await expect(target).toHaveValue('unsaved_target')
  expect(api.calls.filter(({ path }) => path.endsWith('_credential')).map(({ path, body }) => [path, body])).toEqual([
    ['/v1/ops/replace_credential', { name: 'twitch_client_secret', value: 'synthetic-twitch-secret' }],
    ['/v1/ops/test_credential', { name: 'twitch_client_secret' }],
    ['/v1/ops/remove_credential', { name: 'twitch_client_secret' }],
  ])
})

