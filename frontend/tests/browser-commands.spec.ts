test('Commands renders the catalog and creates, edits and deletes a custom command', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 900 })
  const api = await server(page)
  await signIn(page)
  await navigate(page, 'Commands')
  await expect(page.getByRole('heading', { name: 'Commands', level: 1 })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Edit !ping', exact: true })).toBeVisible()

  await selectOption(page.getByRole('combobox', { name: 'Create', exact: true }), 'custom')
  const editor = page.getByRole('dialog').filter({ has: page.getByLabel('Command name', { exact: true }) })
  const save = editor.getByRole('button', { name: 'Save command', exact: true })
  const writePath = '/v1/ops/save_custom_command'
  await editor.getByLabel('Command name', { exact: true }).fill('greet')
  await save.click()
  await expect(editor.getByRole('alert').first()).toBeVisible()
  expect(api.calls.some(({ path }) => path === writePath)).toBe(false)
  await selectOption(editor.getByLabel('Response type', { exact: true }), 'random')
  await selectOption(editor.getByLabel('Send as', { exact: true }), 'mention')
  await editor.getByRole('textbox', { name: 'Responses' }).fill(' Hello, {sender}!\n\n Welcome, {args}! ')
  await editor.getByText('Available variables', { exact: true }).click()
  await expect(editor.getByText('{arg1}…{arg9}', { exact: true })).toBeVisible()
  await expect(editor.getByText('{random_user}', { exact: true })).toBeVisible()
  await expectNoOverflow(page)
  const sections = editor.getByRole('navigation', { name: 'Editor sections' })
  await sections.getByRole('button', { name: 'Access & aliases' }).click()
  await editor.getByLabel('Aliases, separated by commas').fill('hello, welcome')
  await selectOption(editor.getByRole('combobox', { name: 'Permission' }), 'MODERATOR')
  await sections.getByRole('button', { name: 'Conditions' }).click()
  await selectOption(editor.getByLabel('Stream availability'), 'offline_only')
  await expectNoOverflow(page)
  await save.click()
  await expect(editor).toBeHidden()
  expect(api.calls.find(({ path }) => path === writePath)?.body).toMatchObject({
    command: { id: null, name: 'greet', responses: ['Hello, {sender}!', 'Welcome, {args}!'],
      aliases: ['hello', 'welcome'], permission: 'MODERATOR', response_mode: 'random', send_as: 'mention',
      stream_availability: 'offline_only' },
  })

  const edit = page.getByRole('button', { name: 'Edit !greet', exact: true })
  await edit.click()
  const templates = editor.getByRole('textbox', { name: 'Responses' })
  await expect(templates).toHaveValue('Hello, {sender}!\nWelcome, {args}!')
  await templates.fill('Edited message')
  await editor.getByRole('button', { name: 'Close editor' }).click()
  await page.getByRole('dialog', { name: 'Discard unsaved changes?' }).getByRole('button', { name: 'Cancel' }).click()
  await expect(templates).toHaveValue('Edited message')
  await save.click()
  await expect(editor).toBeHidden()
  expect(api.calls.filter(({ path }) => path === writePath).at(-1)?.body).toMatchObject({
    command: { id: 'saved-command', responses: ['Edited message'], aliases: ['hello', 'welcome'] },
  })

  const remove = page.getByRole('button', { name: 'Delete !greet', exact: true })
  const deletion = page.getByRole('dialog').filter({ has: page.getByRole('button', { name: 'Confirm', exact: true }) })
  await remove.click()
  await deletion.getByRole('button', { name: 'Cancel', exact: true }).click()
  expect(api.calls.some(({ path }) => path === '/v1/ops/delete_custom_command')).toBe(false)
  await remove.click()
  await deletion.getByRole('button', { name: 'Confirm', exact: true }).click()
  await expect(edit).toHaveCount(0)
  expect(api.calls.find(({ path }) => path === '/v1/ops/delete_custom_command')?.body).toEqual({ identifier: 'saved-command' })
})

