import { expect, test, type Page } from '@playwright/test'

async function openModels(page: Page, query = '') {
  await page.goto(`/tests/fixture.html?aiAvailable&multipleProviders&${query}`)
  await page.getByRole('button', { name: 'AI', exact: true }).click()
  const models = page.locator('#ai-models')
  await expect(models.getByLabel('Primary model', { exact: true })).toBeVisible()
  return models
}

for (const width of [1280, 390, 320]) {
  test(`provider/model cards and editable instructions fit keyboard layout at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 900 })
    const models = await openModels(page)
    await expect(models.getByRole('heading', { name: 'Connected providers' })).toBeVisible()
    await expect(models.getByLabel('Fallback model', { exact: true })).toBeHidden()
    await models.locator('summary').filter({ hasText: 'Fallback model' }).press('Enter')
    await expect(models.getByLabel('Fallback model', { exact: true })).toBeVisible()
    await models.getByLabel('Primary provider').selectOption('deepseek')
    await models.getByLabel('Primary thinking').selectOption('max')
    await models.getByLabel('Primary internet search').press('Space')
    await expect(models.getByLabel('Primary thinking')).toHaveValue('max')
    await models.locator('summary').filter({ hasText: 'Shared instructions' }).press('Space')
    await models.getByLabel('Shared AI instructions', { exact: true }).fill('Owner edited shared instructions')
    await models.getByLabel('Maximum question length', { exact: true }).fill('1200')
    await models.getByLabel('Maximum answer length', { exact: true }).fill('300')
    await expect(models).toContainText('Local request and full-output checks remain enabled')
    await expect(models.getByRole('button', { name: 'Save AI setup' })).toBeDisabled()
    await models.getByLabel(/I understand that my question/).check()
    await models.getByRole('button', { name: 'Save AI setup' }).click()
    await expect(models).toContainText('AI setup saved')
    await models.screenshot({ path: `node_modules/.tmp/task5-setup-${width}.png` })
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(width)
    await page.reload()
    await page.getByRole('button', { name: 'AI', exact: true }).click()
    await expect(models.getByLabel('Primary provider')).toHaveValue('deepseek')
    await expect(models.getByLabel('Primary thinking')).toHaveValue('max')
    await models.locator('summary').filter({ hasText: 'Shared instructions' }).click()
    await expect(models.getByLabel('Shared AI instructions', { exact: true })).toHaveValue('Owner edited shared instructions')
  })
}

test('switching providers preserves each slot draft and unknown models cannot invent controls', async ({ page }) => {
  const models = await openModels(page)
  await models.getByLabel('Primary model', { exact: true }).fill('gemini-custom')
  await models.getByLabel('Primary provider').selectOption('deepseek')
  await models.getByLabel('Primary thinking').selectOption('low')
  await models.getByLabel('Primary provider').selectOption('gemini')
  await expect(models.getByLabel('Primary model', { exact: true })).toHaveValue('gemini-custom')
  await expect(models.getByLabel('Primary internet search')).toBeDisabled()
  await models.getByLabel('Primary provider').selectOption('deepseek')
  await expect(models.getByLabel('Primary thinking')).toHaveValue('low')
  await models.getByLabel('Primary model', { exact: true }).fill('deepseek-manual')
  await expect(models).toContainText('Unsupported saved choice: low')
  await models.getByLabel('Primary thinking').selectOption('default')
  await expect(models.getByLabel('Primary internet search')).toBeDisabled()
  await models.locator('summary').filter({ hasText: 'Fallback model' }).click()
  await models.getByLabel('Fallback provider').selectOption('deepseek')
  await models.getByLabel('Fallback thinking').selectOption('high')
  await models.getByLabel('Enable fallback', { exact: true }).uncheck()
  await models.getByLabel('Enable fallback', { exact: true }).check()
  await expect(models.getByLabel('Fallback provider')).toHaveValue('deepseek')
  await expect(models.getByLabel('Fallback thinking')).toHaveValue('high')
  expect(await page.evaluate(() => Reflect.get(window, 'aiCalls'))).toEqual([])
})

test('provider discovery failures keep draft and saved choices', async ({ page }) => {
  const models = await openModels(page)
  await models.getByLabel('Primary model', { exact: true }).fill('keep-draft')
  await models.getByRole('button', { name: 'Discover primary models' }).click()
  await expect(models.locator('datalist option[value="gemini-discovered-model"]').first()).toHaveCount(1)
  await expect(models.getByLabel('Primary model', { exact: true })).toHaveValue('keep-draft')
  await page.evaluate(() => { window.pywebview!.api.discover_ai_models = async () => ({ ok: false, error: 'Synthetic discovery failure' }) })
  await models.getByRole('button', { name: 'Discover primary models' }).click()
  await expect(models.getByRole('alert')).toContainText('Synthetic discovery failure')
  await expect(models.getByLabel('Primary model', { exact: true })).toHaveValue('keep-draft')
  await models.getByRole('button', { name: 'Cancel AI edits' }).click()
  await expect(models.getByLabel('Primary model', { exact: true })).toHaveValue('gemini-2.5-flash')
})

test('key connection/removal is immediate, warns for in-use key, and retains unrelated model draft', async ({ page }) => {
  const models = await openModels(page)
  await models.getByLabel('Primary model', { exact: true }).fill('keep-model-draft')
  await models.getByRole('button', { name: 'Replace DeepSeek', exact: true }).click()
  await models.getByLabel('deepseek API key', { exact: true }).fill('synthetic-test-key')
  await models.getByRole('button', { name: 'Save connection' }).click()
  await expect(models.getByLabel('Primary model', { exact: true })).toHaveValue('keep-model-draft')
  await models.getByRole('button', { name: 'Cancel AI edits' }).click()
  await expect(models).toContainText('Saved credentials are unchanged')
  page.once('dialog', async (dialog) => { expect(dialog.message()).toContain('in use'); await dialog.accept() })
  await models.getByRole('button', { name: 'Remove Google Gemini', exact: true }).click()
  await expect(models.getByLabel('Primary provider')).toHaveValue('gemini')
  await expect(models).toContainText('Unavailable: connect this provider')
  await expect(models.locator('input[type=password]')).toHaveCount(0)
})

